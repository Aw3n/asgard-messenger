// ── Find and replace values in each language section ──
const langHeaderRe = /^\s{2}(\w+):\s*\{$/
let currentLang = null
let changesCount = 0

for (let i = 0; i < lines.length; i++) {
  const m = lines[i].match(langHeaderRe)
  if (m) {
    currentLang = m[1]
    continue
  }
  
  if (!currentLang || currentLang === 'fr' || currentLang === 'en') continue
  if (!translations[currentLang]) continue
  
  // Check if this line contains one of our target keys
  const keyMatch = lines[i].match(/^\s{6}"([^"]+)":\s*"(.*)"(,?)\s*$/)
  if (!keyMatch) continue
  
  const key = keyMatch[1]
  if (translations[currentLang][key]) {
    const newValue = translations[currentLang][key].replace(/(?<!\\)"/g, '\\"')
    const comma = keyMatch[3] || ''
    const newLine = `      "${key}": "${newValue}"${comma}`
    if (lines[i] !== newLine) {
      lines[i] = newLine
      changesCount++
    }
  }
}

content = lines.join('\n')
fs.writeFileSync(transPath, content)
console.log(`Updated ${changesCount} translation values across all languages.`)
